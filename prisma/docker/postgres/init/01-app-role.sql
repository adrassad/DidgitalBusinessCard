CREATE ROLE dbc_app LOGIN PASSWORD 'dbc_app';

GRANT CONNECT ON DATABASE dbc TO dbc_app;
GRANT USAGE ON SCHEMA public TO dbc_app;

ALTER DEFAULT PRIVILEGES FOR ROLE dbc IN SCHEMA public
    GRANT SELECT ON TABLES TO dbc_app;
ALTER DEFAULT PRIVILEGES FOR ROLE dbc IN SCHEMA public
    GRANT SELECT ON SEQUENCES TO dbc_app;